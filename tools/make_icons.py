#!/usr/bin/env python3
"""Make the classic Finder icons (ICN#, icl8, ics#, ics8, ICON) as Rez source.

    python3 tools/make_icons.py ../newton_os_on_the_iphone_by_2600rat_d204mz5-fullview.jpg > icons.r

Needs Pillow. The lightbulb is drawn on a black rounded square; colours are
matched to the standard Mac OS 8-bit system palette.
"""
import sys
from PIL import Image, ImageChops, ImageDraw, ImageFilter


def mac_palette():
    levels = [0xFF, 0xCC, 0x99, 0x66, 0x33, 0x00]
    pal = [(r, g, b) for r in levels for g in levels for b in levels][:215]   # cube without black
    ramp = [0xEE, 0xDD, 0xBB, 0xAA, 0x88, 0x77, 0x55, 0x44, 0x22, 0x11]
    pal += [(v, 0, 0) for v in ramp] + [(0, v, 0) for v in ramp] + [(0, 0, v) for v in ramp]
    pal += [(v, v, v) for v in ramp] + [(0, 0, 0)]
    assert len(pal) == 256
    return pal


PAL = mac_palette()


def nearest(rgb):
    return min(range(256), key=lambda i: sum((a - b) ** 2 for a, b in zip(PAL[i], rgb)))


YELLOW = (0xFF, 0xCC, 0x33)   # nearest system-palette colour to the logo's yellow


def render(src, size):
    """Crisp pixel art: solid yellow lines on black, no anti-aliasing."""
    bulb = src.crop((70, 118, 256, 304))              # lightbulb only; the wordmark is unreadable this small
    r, g, b = bulb.split()
    ink = ImageChops.lighter(ImageChops.lighter(r, g), b).point(lambda v: 255 if v > 60 else 0)
    if size <= 16:
        ink = ink.filter(ImageFilter.MaxFilter(3))    # thicken strokes so they survive at 16x16
    inset = 1 if size <= 16 else 2
    cover = ink.resize((size - 2 * inset,) * 2, Image.BOX)
    on = cover.point(lambda v: 255 if v > (90 if size <= 16 else 85) else 0)
    tile = Image.new('RGB', (size, size), (0, 0, 0))
    tile.paste(Image.new('RGB', on.size, YELLOW), (inset, inset), on)
    mask = Image.new('1', (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, size - 1, size - 1), radius=3 if size > 16 else 2, fill=1)
    return tile, mask


def bits(img_fn, size):
    out = bytearray()
    for y in range(size):
        row = 0
        for x in range(size):
            row = row << 1 | (1 if img_fn(x, y) else 0)
        out += row.to_bytes(size // 8, 'big')
    return bytes(out)


def hexdata(b, per=16):
    return '\n'.join('\t$"%s"' % ' '.join(b[i:i + per][j:j + 2].hex().upper()
                                          for j in range(0, len(b[i:i + per]), 2))
                     for i in range(0, len(b), per))


def main():
    src = Image.open(sys.argv[1]).convert('RGB')
    print('/* Generated by tools/make_icons.py -- do not edit by hand. */\n')
    for size, (bw, col) in ((32, ('ICN#', 'icl8')), (16, ('ics#', 'ics8'))):
        tile, mask = render(src, size)
        px, m = tile.load(), mask.load()
        # 1-bit: black square, light parts of the bulb left white
        icon = bits(lambda x, y: m[x, y] and px[x, y] != YELLOW, size)
        maskb = bits(lambda x, y: m[x, y], size)
        print(f"data '{bw}' (128) {{\n{hexdata(icon + maskb)}\n}};\n")
        col8 = bytes(nearest(px[x, y]) if m[x, y] else 0 for y in range(size) for x in range(size))
        print(f"data '{col}' (128) {{\n{hexdata(col8)}\n}};\n")
        if size == 32:
            print(f"data 'ICON' (128) {{\n{hexdata(icon)}\n}};\n")


if __name__ == '__main__':
    main()
